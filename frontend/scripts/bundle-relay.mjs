#!/usr/bin/env node
/**
 * Packs the relay (../relay/worker) into worker/relay-source.js, so the
 * website's Worker can install it into a visitor's Cloudflare account.
 * Runs as part of `npm run build`. The output is generated, not committed.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const relay = join(here, '../../relay');
const toml = readFileSync(join(relay, 'wrangler.toml'), 'utf8');
const setting = (key) => {
  const m = new RegExp(`^${key}\\s*=\\s*"([^"]*)"`, 'm').exec(toml);
  if (!m) throw new Error(`relay/wrangler.toml has no ${key}`);
  return m[1];
};

const files = {};
for (const name of readdirSync(join(relay, 'worker'))) {
  if (name.endsWith('.js')) files[name] = readFileSync(join(relay, 'worker', name), 'utf8');
}
if (!files['index.js']) throw new Error('relay/worker/index.js is missing');

const out = `// Generated by scripts/bundle-relay.mjs from ../relay. Do not edit.
export const RELAY = ${JSON.stringify(
  {
    name: setting('name'),
    compatibilityDate: setting('compatibility_date'),
    turnHosts: setting('TURN_HOSTS'),
    files,
  },
  null,
  2,
)};
`;
writeFileSync(join(here, '../worker/relay-source.js'), out);
console.log(`bundled the relay (${Object.keys(files).join(', ')})`);
